const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const schema = fs.readFileSync(path.resolve(__dirname, '../../db/schema.sql'), 'utf8');
const migrationPath = path.resolve(__dirname, '../../db/migrations/20261104205039_casting_call_drafts.sql');
const fields = ['title', 'description', 'positions_count', 'min_age', 'max_age', 'location', 'application_deadline'];

// Only temporary tables are changed, even when backend/.env points to a shared DB.
test('Casting drafts: initial schema and migration enforce the same contract', {
  skip: process.env.CASTING_DATABASE_TESTS !== '1' ? 'Run npm run test:db:casting.' : false,
}, async t => {
  const pool = require('../src/config/db');
  const client = await pool.connect();
  t.after(async () => { client.release(); await pool.end(); });
  await client.query('CREATE TEMP TABLE projects (id INT PRIMARY KEY)');
  await client.query('INSERT INTO projects VALUES (1), (2)');
  await client.query('SET search_path = pg_temp, public');

  const createTable = schema.match(/CREATE TABLE casting_calls\s*\([\s\S]*?\n\);/)[0]
    .replace('CREATE TABLE', 'CREATE TEMP TABLE');
  const constraints = schema.match(/ALTER TABLE casting_calls\s+[\s\S]*?;/)[0];
  const legacyTable = `CREATE TEMP TABLE casting_calls (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL, description VARCHAR(2000) NOT NULL,
    positions_count INT NOT NULL, max_applications INT NOT NULL DEFAULT 1000,
    audition_text VARCHAR(5000), min_age INT NOT NULL, max_age INT NOT NULL,
    appearance_req VARCHAR(1000), exp_req VARCHAR(1000), location VARCHAR(200) NOT NULL,
    application_deadline TIMESTAMPTZ NOT NULL, status VARCHAR(25) NOT NULL,
    published_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    project_id INT NOT NULL REFERENCES projects(id),
    CONSTRAINT positions_positive CHECK (positions_count > 0),
    CONSTRAINT max_applications_positive CHECK (max_applications > 0),
    CONSTRAINT age_range CHECK (min_age >= 18 AND max_age >= min_age),
    CONSTRAINT project_unique UNIQUE (project_id)
  )`;
  const complete = ['Role', 'Description', 2, 18, 60, 'Zagreb', '2030-12-01T12:00:00Z'];
  const insert = (values = complete, status = 'published', projectId = 1) => client.query(
    `INSERT INTO casting_calls (${fields.join(', ')}, status, project_id)
     VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9) RETURNING *`,
    [...values, status, projectId],
  );
  let initialContract;
  const contract = async () => ({
    columns: (await client.query(`SELECT attname, attnotnull FROM pg_attribute
      WHERE attrelid = 'pg_temp.casting_calls'::regclass AND attnum > 0 ORDER BY attnum`)).rows,
    checks: (await client.query(`SELECT conname, pg_get_constraintdef(oid) AS definition
      FROM pg_constraint WHERE conrelid = 'pg_temp.casting_calls'::regclass AND contype = 'c'
      ORDER BY conname`)).rows,
  });

  for (const mode of ['initial schema', 'migration']) {
    await t.test(mode, async t => {
      if (mode === 'initial schema') {
        await client.query(createTable);
        await client.query(constraints);
        initialContract = await contract();
      } else {
        await client.query(legacyTable);
        await insert();
        const before = (await client.query('SELECT * FROM casting_calls')).rows;
        const migration = fs.readFileSync(migrationPath, 'utf8');
        await client.query(migration);
        assert.deepEqual((await client.query('SELECT * FROM casting_calls')).rows, before);
        await client.query(migration); // Safe to run the migration command again.
        assert.deepEqual(await contract(), initialContract);
        await client.query('TRUNCATE pg_temp.casting_calls');
      }

      await t.test('save, edit and publish an incomplete draft', async () => {
        const { rows: [draft] } = await client.query(
          "INSERT INTO casting_calls (project_id, status) VALUES (1, 'draft') RETURNING *",
        );
        for (const field of fields) assert.equal(draft[field], null);
        assert.equal(draft.max_applications, 1000);
        await client.query("UPDATE casting_calls SET description = 'In progress' WHERE id = $1", [draft.id]);
        await assert.rejects(client.query("UPDATE casting_calls SET status = 'published' WHERE id = $1", [draft.id]),
          { code: '23514', constraint: 'casting_calls_complete_unless_draft' });
        await client.query(`UPDATE casting_calls SET ${fields.map((field, i) => `${field} = $${i + 1}`).join(', ')}
          WHERE id = $8`, [...complete, draft.id]);
        await client.query("UPDATE casting_calls SET status = 'published' WHERE id = $1", [draft.id]);
        await assert.rejects(client.query('UPDATE casting_calls SET location = NULL WHERE id = $1', [draft.id]),
          { code: '23514', constraint: 'casting_calls_complete_unless_draft' });
        await client.query('TRUNCATE pg_temp.casting_calls');
      });

      await t.test('every required field rejects NULL outside draft; text rejects whitespace', async () => {
        for (const status of ['published', 'closed', 'filled', 'cancelled']) {
          for (let i = 0; i < fields.length; i++) {
            const values = [...complete];
            values[i] = null;
            await assert.rejects(insert(values, status),
              { code: '23514', constraint: 'casting_calls_complete_unless_draft' });
          }
          for (const field of ['title', 'description', 'location']) {
            for (const blank of ['', ' ', '\t\n']) {
              const values = [...complete];
              values[fields.indexOf(field)] = blank;
              await assert.rejects(insert(values, status),
                { code: '23514', constraint: 'casting_calls_complete_unless_draft' });
            }
          }
          await insert(complete, status);
          await client.query('TRUNCATE pg_temp.casting_calls');
        }
      });

      await t.test('drafts still enforce ages, counts, status, project and uniqueness', async () => {
        const empty = fields.map(() => null);
        for (const [field, value, constraint] of [
          ['min_age', 17, 'age_range'], ['max_age', 17, 'age_range'],
          ['positions_count', 0, 'positions_positive'], ['positions_count', -1, 'positions_positive'],
        ]) {
          const values = [...empty];
          values[fields.indexOf(field)] = value;
          await assert.rejects(insert(values, 'draft'), { code: '23514', constraint });
        }
        await assert.rejects(insert([null, null, null, 40, 30, null, null], 'draft'),
          { code: '23514', constraint: 'age_range' });
        await insert([null, null, null, 18, null, null, null], 'draft');
        await insert([null, null, null, null, 18, null, null], 'draft', 2);
        await assert.rejects(insert(empty, 'draft'), { code: '23505' });
        await client.query('TRUNCATE pg_temp.casting_calls');
        await assert.rejects(insert(empty, null), { code: '23502' });
        await assert.rejects(insert(empty, 'draft', null), { code: '23502' });
        await assert.rejects(insert(empty, 'draft', 999), { code: '23503' });
        await assert.rejects(client.query("INSERT INTO casting_calls (project_id, status, max_applications) VALUES (1, 'draft', 0)"),
          { code: '23514', constraint: 'max_applications_positive' });
        await assert.rejects(client.query("INSERT INTO casting_calls (project_id, status, max_applications) VALUES (1, 'draft', NULL)"),
          { code: '23502' });
      });
      await client.query('DROP TABLE pg_temp.casting_calls');
    });
  }

  await t.test('invalid existing data rolls the migration back without losing rows', async () => {
    await client.query(legacyTable);
    const values = [...complete];
    values[fields.indexOf('description')] = '   ';
    await insert(values);
    const before = (await client.query('SELECT * FROM casting_calls')).rows;
    await assert.rejects(client.query(fs.readFileSync(migrationPath, 'utf8')),
      { code: '23514', constraint: 'casting_calls_complete_unless_draft' });
    await client.query('ROLLBACK');
    assert.deepEqual((await client.query('SELECT * FROM casting_calls')).rows, before);
    await assert.rejects(client.query("INSERT INTO casting_calls (project_id, status) VALUES (2, 'draft')"),
      { code: '23502' });
    const { rows } = await client.query(`SELECT count(*)::int AS n FROM pg_constraint
      WHERE conrelid = 'pg_temp.casting_calls'::regclass AND conname = 'casting_calls_complete_unless_draft'`);
    assert.equal(rows[0].n, 0);
  });
});
