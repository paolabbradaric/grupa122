-- Dopuna postojećih verifikacija; stare odluke i njihovi autori ostaju sačuvani.
ALTER TABLE verification ADD COLUMN IF NOT EXISTS submitted_data JSONB;
CREATE INDEX IF NOT EXISTS verification_latest_idx ON verification(org_id, submitted_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS casting_reports (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  casting_call_id INT REFERENCES casting_calls(id),
  casting_title VARCHAR(200) NOT NULL,
  reporter_id INT NOT NULL REFERENCES users(id),
  reason VARCHAR(2000) NOT NULL CHECK (length(btrim(reason)) BETWEEN 1 AND 2000),
  status VARCHAR(15) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'dismissed', 'removed')),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ,
  reviewed_by INT REFERENCES users(id),
  review_note VARCHAR(2000)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_open_casting_report
  ON casting_reports(reporter_id, casting_call_id) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS casting_reports_status_idx ON casting_reports(status, submitted_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS casting_reports_casting_idx ON casting_reports(casting_call_id);

CREATE SCHEMA IF NOT EXISTS app_private;
CREATE TABLE IF NOT EXISTS app_private.moderation_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id INT NOT NULL REFERENCES users(id),
  action VARCHAR(50) NOT NULL,
  entity_id INT NOT NULL,
  reason VARCHAR(2000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Vanjski objekt briše se tek nakon COMMIT-a. Neuspjeh ostavlja posao za ponovni pokušaj.
CREATE TABLE IF NOT EXISTS app_private.moderation_file_cleanup (
  storage_key VARCHAR(500) PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  attempts INT NOT NULL DEFAULT 0
);
ALTER TABLE verification ENABLE ROW LEVEL SECURITY;
ALTER TABLE casting_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.moderation_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_private.moderation_file_cleanup ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC;
REVOKE ALL ON verification, casting_reports, app_private.moderation_events,
  app_private.moderation_file_cleanup FROM PUBLIC;
DO $$ DECLARE api_role TEXT; BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
      EXECUTE format('REVOKE ALL ON verification, casting_reports, app_private.moderation_events, app_private.moderation_file_cleanup FROM %I', api_role);
    END IF;
  END LOOP;
END $$;
